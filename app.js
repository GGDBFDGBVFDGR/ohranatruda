  function renderQuiz() {
    const root = document.getElementById("quiz");
    if (finished) {
      root.innerHTML = `
        <p class="score">${score} / ${QUIZ.length}</p>
        <p>${t("correct")}</p>
        <p>${RESULT[lang][resultBand()]}</p>
        <button class="btn btn-primary" type="button" id="restart">${t("restart")}</button>`;
      return;
    }
    const quiz = QUIZ[qIndex][lang];
    root.innerHTML = `
      <p class="kicker">${t("question")} ${qIndex + 1} / ${QUIZ.length}</p>
      <div class="bar" aria-hidden="true"><span style="width:${(qIndex / QUIZ.length) * 100}%"></span></div>
      <h3>${quiz.q}</h3>
      <div class="options">
        ${quiz.options.map((option, index) => `<button type="button" class="option" data-option="${index}">${option}</button>`).join("")}
      </div>
      <p class="explain" id="explain" ${locked ? "" : "hidden"}></p>
      <div class="quiz-nav"><button class="btn btn-primary" type="button" id="quiz-next" ${locked ? "" : "hidden"}>${qIndex === QUIZ.length - 1 ? t("seeResult") : t("nextQ")}</button></div>`;
    if (!locked) return;
    root.querySelectorAll(".option").forEach((button, option) => {
      button.disabled = true;
      if (option === QUIZ[qIndex].answer) button.classList.add("is-correct");
      if (option === picked && option !== QUIZ[qIndex].answer) button.classList.add("is-wrong");
    });
    const explain = document.getElementById("explain");
    explain.hidden = false;
    explain.textContent = QUIZ[qIndex][lang].explain;
  }

  function answer(index) {
    if (locked) return;
    locked = true;
    picked = index;
    const buttons = document.querySelectorAll(".option");
    buttons.forEach((button, option) => {
      button.disabled = true;
      if (option === QUIZ[qIndex].answer) button.classList.add("is-correct");
    });
    if (index === QUIZ[qIndex].answer) score += 1;
    else buttons[index].classList.add("is-wrong");
    const explain = document.getElementById("explain");
    explain.hidden = false;
    explain.textContent = QUIZ[qIndex][lang].explain;
    document.getElementById("quiz-next").hidden = false;
  }

  function tiltProtocol(event) {
    const card = document.getElementById("protocol");
    if (!card || window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
    const rect = card.getBoundingClientRect();
    const x = (event.clientX - rect.left) / rect.width - 0.5;
    const y = (event.clientY - rect.top) / rect.height - 0.5;
    card.style.transform = `rotateY(${x * 7}deg) rotateX(${-y * 6}deg)`;
  }


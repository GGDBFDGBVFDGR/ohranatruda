  function norm(angle) {
    let value = angle % 360;
    if (value > 180) value -= 360;
    if (value < -180) value += 360;
    return value;
  }

  function frontIndex() {
    const step = 360 / LABS.length;
    let best = 0;
    let bestAbs = 999;
    LABS.forEach((_, index) => {
      const delta = Math.abs(norm(spin + index * step));
      if (delta < bestAbs) {
        bestAbs = delta;
        best = index;
      }
    });
    return best;
  }

  function layoutCarousel() {
    const stage = document.getElementById("stage");
    const cards = stage.querySelectorAll(".lab-card");
    const step = 360 / LABS.length;
    const radius = Math.max(168, Math.min(360, stage.clientWidth * 0.34));
    cards.forEach((card, index) => {
      const angle = spin + index * step;
      const depth = Math.cos((angle * Math.PI) / 180);
      card.style.transform = `rotateY(${angle}deg) translateZ(${radius}px)`;
      card.style.opacity = depth < -0.2 ? "0" : String(0.25 + 0.75 * Math.max(depth, 0));
      card.style.zIndex = String(100 + Math.round(depth * 40));
      card.style.pointerEvents = depth > 0.45 ? "auto" : "none";
      card.classList.toggle("is-front", index === labIndex);
      card.setAttribute("aria-pressed", index === labIndex ? "true" : "false");
    });
  }

